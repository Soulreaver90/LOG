assert all(len(r) == 32 for r in head), [(i, len(r)) for i, r in enumerate(head) if len(r) != 32]
rows[:len(head)] = head
Path(__file__).with_name(OUT).write_text("\n".join(rows) + "\n")
for i, r in enumerate(rows[:18]):
    print("%2d %s" % (i, r))
