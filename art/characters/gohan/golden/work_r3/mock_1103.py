def put(base_rows, head, name):
    h = [r for r in head.splitlines() if r]
    assert all(len(r) == 32 for r in h), (name, [(i, len(r)) for i, r in enumerate(h) if len(r) != 32])
    rows = h + base_rows[len(h):]
    p = Path(__file__).with_name(name + ".txt"); p.write_text("\n".join(rows) + "\n")
    return from_txt(p)


