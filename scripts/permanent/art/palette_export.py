r"""palette_export.py - Write the LoG II palettes as GIMP .gpl files for Aseprite and friends.

Usage:   py -3.14 -P scripts\permanent\art\palette_export.py <out_dir> [--rom <path>]
Writes:  log2-obj-256.gpl  the shared OBJ palette (sprites). This is the one for sprite work.
         log2-bg-256.gpl   the shared BG palette (map tiles).
         Both carry all 256 slots IN ORDER, so slot N in the editor is ROM palette index N.
Colour:  BGR555 to RGB as (channel & 31) * 8, the same conversion log2_sprites.tiles_to_image uses,
         so a colour picked here matches our exported frame PNGs exactly and converts back with // 8.
Rom:     Defaults to the base USA ROM. Pass --rom to read a BUILD, because art_inject writes OBJ
         palette entries, so a build's palette is not always the base ROM's.
Slots:   OBJ index 0 and index 168 are set at run time, not from this table (bible B0250). Index 0 is
         the transparent slot in every sprite frame, so never paint with it.
"""
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # scripts\permanent: -P omits the script folder
import log_paths  # noqa: E402

# ===== constants =====
OBJ_PAL, BG_PAL, ENTRIES = 0x1DA6C8, 0x1DA4C8, 256
RUNTIME_OBJ = {0: "transparent, set at run time", 168: "set at run time"}
DEFAULT_ROM = log_paths.BASE_ROM


# ===== conversion =====
def colours(rom: bytes, at: int) -> list:
    """256 (r, g, b) tuples from BGR555, matching tiles_to_image."""
    out = []
    for i in range(ENTRIES):
        c = struct.unpack_from("<H", rom, at + i * 2)[0]
        out.append(((c & 31) * 8, (c >> 5 & 31) * 8, (c >> 10 & 31) * 8))
    return out


def write_gpl(path: Path, name: str, cols: list, notes: dict) -> None:
    """A .gpl with one line per slot, named by its true ROM index so nothing shifts."""
    lines = ["GIMP Palette", f"Name: {name}", "Columns: 16",
             "# Slot order is ROM palette index order. Slot N here is ROM index N.",
             "# Generated by scripts/permanent/art/palette_export.py"]
    for i, (r, g, b) in enumerate(cols):
        label = f"{i}" + (f"  ({notes[i]})" if i in notes else "")
        lines.append(f"{r:3d} {g:3d} {b:3d}\t{label}")
    path.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    print("wrote", path)


# ===== entry point =====
def main(argv) -> None:
    if not argv:
        print(__doc__)
        return
    out = Path(argv[0])
    out.mkdir(parents=True, exist_ok=True)
    rom_path = Path(argv[argv.index("--rom") + 1]) if "--rom" in argv else DEFAULT_ROM
    rom = rom_path.read_bytes()
    print("read", rom_path, f"({len(rom)} bytes)")
    write_gpl(out / "log2-obj-256.gpl", "LoG II OBJ palette (sprites, 256 slots)",
              colours(rom, OBJ_PAL), RUNTIME_OBJ)
    write_gpl(out / "log2-bg-256.gpl", "LoG II BG palette (map tiles, 256 slots)",
              colours(rom, BG_PAL), {})


if __name__ == "__main__":
    main(sys.argv[1:])
