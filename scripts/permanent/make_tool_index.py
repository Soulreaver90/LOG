r"""Regenerate docs\tool-index.md from the scripts on disk.

Why it is generated: a hand kept index rots, and a rotted index is worse than none. On 2026-11-02 two
scripts named derive.py were written for the same job because nothing listed the first one.

Each tool's entry is the first line of its module docstring, so a tool documents itself. A tool that
defines SUPERSEDED_BY = "<what replaced it>" is listed as retired and must also carry an exit guard.

Run: py -3.14 -P scripts\permanent\make_tool_index.py
"""
import ast
import datetime as dt
from pathlib import Path

LOG = Path(__file__).resolve().parents[2]
PERM = LOG / "scripts" / "permanent"
ONCE = LOG / "scripts" / "one-time"
OUT = LOG / "docs" / "tool-index.md"
STATS = {}                      # what the last build() counted, for main() to print

# One line per folder of tools. A folder with no line here is still listed, with a plain note.
FOLDER_NOTES = {
    "rom": "Read and write the ROM: sprites, saves, compression, free space.",
    "scene": "Cutscenes: read one, write one, draw a map, run one in a test.",
    "disasm": "The project's own disassembler, for reading game code.",
    "map-editor": "Compose a map by eye in the browser, then put it in the ROM.",
    "emu": "Drive mGBA: run a build, capture a frame, read its memory.",
    "review": "Build the sheets the owner looks at before art ships.",
    "ghidra": "Scripts for the Ghidra project, run inside Ghidra and not from here.",
}


def purpose(p: Path) -> tuple[str, str]:
    """First docstring line plus any TOOL_INDEX_NOTE, and the SUPERSEDED_BY value.

    A trap worth a line in the index is longer than a purpose line and must not be truncated with it,
    so a tool declares it as TOOL_INDEX_NOTE = "..." and this appends it after the 150 char cut. The
    index is GENERATED, so a note typed into docs\\tool-index.md by hand is wiped on the next run.
    """
    try:
        tree = ast.parse(p.read_text(encoding="utf-8", errors="replace"))
    except SyntaxError:
        return "(will not parse)", ""
    doc = ast.get_docstring(tree) or ""
    first = next((ln.strip() for ln in doc.splitlines() if ln.strip()), "")
    first = first.split(" - ", 1)[-1] if first.startswith(p.name) else first
    dead, note = "", ""
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Constant):
            names = [getattr(t, "id", "") for t in node.targets]
            if "SUPERSEDED_BY" in names:
                dead = str(node.value.value)
            if "TOOL_INDEX_NOTE" in names:
                note = str(node.value.value)
    text = first[:150] or "(no docstring)"
    return (f"{text} {note}" if note else text), dead


def table(rows, head):
    out = [f"| {' | '.join(head)} |", f"|{'---|' * len(head)}"]
    out += [f"| {' | '.join(r)} |" for r in rows]
    return out


def group(folder: Path, title: str, note: str) -> list[str]:
    files = sorted(p for p in folder.glob("*.py") if p.name != "__init__.py")
    if not files:
        return []
    rows = []
    for p in files:
        text, dead = purpose(p)
        rows.append([f"`{p.name}`", (f"**RETIRED, use {dead}.** " if dead else "") + text])
    return [f"### {title}", "", note, ""] + table(rows, ["Tool", "What it does"]) + [""]


def tool_folders() -> list:
    r"""Every subfolder of scripts\permanent that holds tools, read from disk and never listed.

    A fixed tuple here is what left map-editor, emu, review and ghidra out of the index from the
    day each was created, so nothing found them in the search CLAUDE.md asks for first. The four
    names below are left out for a reason, not by omission: tests are not tools, patches and art
    have their own sections, and __pycache__ is not source."""
    skip = {"tests", "patches", "art", "__pycache__"}
    return sorted(d for d in PERM.iterdir()
                  if d.is_dir() and d.name not in skip and any(d.glob("*.py")))


def build() -> list[str]:
    L = ["# Tool index", "",
         "Every reusable script in the project, with what it does. **Search this before you write a "
         "script.** If a tool already does the job, run it or extend it. Do not write a second one.", "",
         rf"Generated by `scripts\permanent\make_tool_index.py`. Last run {dt.date.today():%Y-%m-%d}. "
         "Re-run it after adding or retiring a tool.", "",
         "A tool marked SUPERSEDED still exists but must not be run. Its docstring says what replaced it.",
         "", "---", ""]

    L += group(PERM, "Build and top level", "The build script, the index generator and friends.")
    for folder in tool_folders():
        L += group(folder, rf"`scripts\permanent\{folder.name}\`",
                   FOLDER_NOTES.get(folder.name, "Tools in this folder."))

    patches = sorted((PERM / "patches").glob("*.py"))
    if patches:
        rows = [[f"`{p.name}`", purpose(p)[0]] for p in patches]
        L += [f"### Patches ({len(patches)})", "",
              "One file per change to the game. A build list names these in order.", ""]
        L += table(rows, ["Patch", "What it changes"]) + [""]

    # Generators that write into art\ deserve their own section: these are the dangerous ones.
    documented, bare = [], {}
    for p in sorted(LOG.glob("art/**/*.py")):
        text, dead = purpose(p)
        rel = f"`{p.relative_to(LOG)}`".replace("/", "\\")
        if text == "(no docstring)":
            bare.setdefault(str(p.parent.relative_to(LOG)).replace("/", "\\"), []).append(p.name)
        else:
            documented.append([rel, (f"**RETIRED, use {dead}.** " if dead else "") + text])
    L += ["### Generators that build art", "",
          "These derive approved art from vanilla plus a hand drawing. A stale one silently rebuilds "
          "old pixels, so each must either match the shipped file or carry an exit guard.", ""]
    if documented:
        L += table(documented, ["Script", "What it does"]) + [""]
    if bare:
        n = sum(len(v) for v in bare.values())
        L += [rf"**{n} scripts under `art\` carry no docstring, so nothing here can say what they do "
              f"or whether they are safe to run.** Treat every one as unknown until it is documented "
              f"or deleted.", ""]
        L += table([[f"`{k}`", str(len(v))] for k, v in sorted(bare.items())],
                   ["Folder", "Undocumented scripts"]) + [""]

    folders = sorted((d for d in ONCE.iterdir() if d.is_dir()), reverse=True)
    L += [f"### One-time work ({len(folders)} dated folders, "
          f"{len(list(ONCE.glob('**/*.py')))} scripts)", "",
          "Scripts written to answer one question, kept with the answers they printed. Not reusable "
          "by default, but check here before re-deriving a ROM fact: the answer may already be "
          "printed in a `.txt` beside the script. Newest first.", ""]
    rows = []
    for d in folders[:40]:
        n = len(list(d.glob("**/*.py")))
        notes = sorted(d.glob("*.md"))
        rows.append([f"`{d.name}`", str(n), notes[0].name if notes else ""])
    L += table(rows, ["Folder", "Scripts", "Notes file"])
    if len(folders) > 40:
        L += ["", rf"...and {len(folders) - 40} older folders in `scripts\one-time\`."]
    L += [""]

    STATS.update(tools=len(list(PERM.glob("*.py")))
                 + sum(len(list(d.glob("*.py"))) for d in tool_folders()),
                 folders=[d.name for d in tool_folders()], patches=len(patches),
                 art=len(documented), bare=sum(len(v) for v in bare.values()), once=len(folders))
    return L


def main() -> int:
    """Write the index and print what went into it. `build` reads, so a test can run it safely."""
    text = "\n".join(build())
    OUT.write_text(text, encoding="utf-8")
    print(f"  wrote {OUT.relative_to(LOG)}  ({len(text)} bytes)")
    print(f"  permanent tools indexed: {STATS['tools']}   folders: {', '.join(STATS['folders'])}")
    print(f"  patches: {STATS['patches']}   art generators documented: {STATS['art']}, "
          f"undocumented: {STATS['bare']}   one-time folders: {STATS['once']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
